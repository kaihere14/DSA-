class Solution {
    public long countCommas(long n) {
        /*
        1–999 → 0 commas
        
        1,000–999,999 → 1 comma

        1,000,000 –9 99,999,999 → 2 commas
 
        1,000,000,000–999,999,999, 999 → 3 commas

        1,000,000,000,000–999,999,999,999,999 → 4 commas

        1,000,000,000,000,000–999,999,999,999,999,999
         */
 
        if (n < 1000) return 0;
        else if (n < 1000000) return (n - 999);
        else if (n < 1000000000) return 999000 + (n - 999999) * 2;
        else if (n < 1000000000000L) return 999000 + 1998000000L + (n - 999999999) * 3;
        else if (n < 1000000000000000L) return 999000 + 1998000000L + 2997000000000L + (n - 999999999999L) * 4;
        else return 3998998998999000L + 5;
    }
}